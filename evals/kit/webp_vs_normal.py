"""How much data the kit's photo saves: the photo sent the normal way (the file itself, or the 400 px "small
picture") against the kit's 128 px grey WebP sent as SMS codes, and a colour close-up of a quarter of it (what the
look-closer loop asks for). Real encodes of the sample photos, nothing estimated.

    .venv/bin/python evals/kit/webp_vs_normal.py      # prints the table and writes evals/kit/WEBP_VS_NORMAL.md
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
sys.path.insert(0, ROOT)
from PIL import Image  # noqa: E402

from evac import codes, imagemap, smsimage  # noqa: E402

SMS = 140  # bytes one SMS carries on the air
PHOTOS = [("Black widow", "spiders/black_widow"), ("False widow", "spiders/false_widow"),
          ("Downed power line", "redhook/downed_line"), ("Flooded corner", "redhook/flooded_corner"),
          ("Apple", "Apple"), ("Bicycle", "Bicycle"), ("Dog", "Dog"), ("Mug", "Mug"), ("Sneaker", "Sneaker"), ("Teapot", "Teapot")]


def kb(b):
    return "%d B" % b if b < 1000 else "%.1f KB" % (b / 1000)


def measure(name, rel):
    path = os.path.join(ROOT, "sim", "samples", rel + ".jpg")
    img = Image.open(path).convert("RGB")
    grey = smsimage.webp(img)
    sms = codes.sms_parts(codes.text(codes.parts("P", grey, "ab")))
    w, h = smsimage.fit(img).size  # a colour close-up of the middle quarter, cropped from the original
    data = codes.crop_zoom(img, (0, 0, img.width, img.height), (w, h), [w * 3 // 8, h * 3 // 8, w // 4, h // 4], colour=True)[0]
    zoom_sms = codes.sms_parts(codes.text(codes.parts("Z", codes.zoom_head("ab", (0, 0, 1, 1)) + data, "az")))
    original = os.path.getsize(path)
    return {"name": name, "px": "%d×%d" % img.size, "original": original, "small": imagemap.shrink(img)["bytes"],
            "webp": len(grey), "sms": sms, "zoom": len(data), "zoom_sms": zoom_sms, "saving": original / (sms * SMS)}


def main():
    rows = [measure(*p) for p in PHOTOS]
    lines = ["| Photo | Sent normally (the file) | Small picture (400 px WebP) | Kit: 128 px grey WebP | As SMS | Saving vs the file | + one colour close-up |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append("| %s | %s (%s) | %s | %s | %d SMS = %s | %.0f× | %s = %d SMS |" % (
            r["name"], kb(r["original"]), r["px"], kb(r["small"]), kb(r["webp"]), r["sms"], kb(r["sms"] * SMS),
            r["saving"], kb(r["zoom"]), r["zoom_sms"]))
    table = "\n".join(lines)
    print(table)
    with open(os.path.join(os.path.dirname(__file__), "WEBP_VS_NORMAL.md"), "w") as f:
        f.write("# The kit's photo against sending it normally (measured)\n\nGenerated by `evals/kit/webp_vs_normal.py`. "
                "One SMS = %d bytes on the air; the SMS count includes the code's base64 and headers. A phone's own "
                "photo is 2-4 MB, about ten times these samples, so the saving against a real photo is larger.\n\n%s\n" % (SMS, table))


if __name__ == "__main__":
    main()
